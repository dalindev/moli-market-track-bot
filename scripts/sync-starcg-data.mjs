#!/usr/bin/env node
// Regenerates src/data/equipment-stats.ts from the wodenchen/StarCG data files.
//
// Source of truth is the FORK (github.com/dalindev/StarCG), which tracks upstream via a
// `upstream` remote. To pull newer game data:
//
//     cd ../StarCG            # or wherever the fork is cloned
//     git fetch upstream && git merge upstream/main
//     cd -                     && node scripts/sync-starcg-data.mjs
//
// The fork is kept as a clean mirror on purpose — no local edits — so that merge is always a
// fast-forward. Everything we add lives in THIS repo, so upstream can never conflict with it.
//
// Upstream's equipment.json declares its own origin as https://guide.starcg.net/equipment/,
// so these numbers are a cached view of the public game guide.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');

// Where the fork is checked out. Override with STARCG_FORK=/path/to/StarCG.
const FORK = process.env.STARCG_FORK ?? resolve(REPO, '../../../StarCG');
const RAW = 'https://raw.githubusercontent.com/dalindev/StarCG/main';

async function loadSource(file) {
  const local = resolve(FORK, file);
  if (existsSync(local)) return { text: readFileSync(local, 'utf8'), from: local };
  const res = await fetch(`${RAW}/${file}`);
  if (!res.ok) throw new Error(`cannot read ${file}: local miss and HTTP ${res.status}`);
  return { text: await res.text(), from: `${RAW}/${file}` };
}

/** Evaluates upstream's plain-script data file and pulls the globals out of it. */
function evalDataScript(src, names) {
  const fn = new Function(`${src}\nreturn {${names.join(',')}};`);
  return fn();
}

const maxStatsSrc = await loadSource('equipment_max_stats.js');
const catalogSrc = await loadSource('equipment.json');

const { EQUIPMENT_MAX_STATS, EQUIPMENT_STAT_LABELS } = evalDataScript(maxStatsSrc.text, [
  'EQUIPMENT_MAX_STATS',
  'EQUIPMENT_STAT_LABELS',
]);
const catalog = JSON.parse(catalogSrc.text);

const versionMatch = maxStatsSrc.text.match(/@version\s+(\S+)/);
const dataVersion = versionMatch ? versionMatch[1] : 'unknown';

// equipment.json carries per-stat [min,max] ranges, which beat a bare max: a roll is only
// impressive relative to how far the range actually spans.
const CATALOG_TO_ITEM_KEY = {
  atk: 'ITEM_MODIFYATTACK', def: 'ITEM_MODIFYDEFENCE', agi: 'ITEM_MODIFYAGILITY',
  hp: 'ITEM_MODIFYHP', mp: 'ITEM_MODIFYFORCEPOINT', rec: 'ITEM_MODIFYRECOVERY',
  spt: 'ITEM_MODIFYMAGIC', matk: 'ITEM_ADM', amres: 'ITEM_RSS',
  crit: 'ITEM_MODIFYCRITICAL', hit: 'ITEM_MODIFYHITRATE',
  counter: 'ITEM_MODIFYCOUNTER', dodge: 'ITEM_MODIFYAVOID',
};

const ranges = {};
const levels = {};
for (const item of catalog.items ?? []) {
  if (!item?.name || !item.ranges) continue;
  const mapped = {};
  for (const [k, v] of Object.entries(item.ranges)) {
    const key = CATALOG_TO_ITEM_KEY[k];
    if (key && Array.isArray(v) && v.length === 2) mapped[key] = [v[0], v[1]];
  }
  if (Object.keys(mapped).length > 0) ranges[item.name] = mapped;
  if (typeof item.level === 'number') levels[item.name] = item.level;
}

// Upstream nests a `byItemId` variant map for one item (英靈之誓). Keep it verbatim.
const flatCount = Object.values(EQUIPMENT_MAX_STATS).filter((v) => !v.byItemId).length;

const out = `// GENERATED by scripts/sync-starcg-data.mjs — do not edit by hand.
//
// Source: github.com/dalindev/StarCG (fork of wodenchen/StarCG), data version ${dataVersion},
// which cites https://guide.starcg.net/equipment/ as its own origin.
// Re-run the script after merging upstream to pick up new game data.
//
// ${Object.keys(EQUIPMENT_MAX_STATS).length} equipment entries (${flatCount} flat, ${Object.keys(EQUIPMENT_MAX_STATS).length - flatCount} with per-itemId variants),
// ${Object.keys(ranges).length} with per-stat [min, max] ranges, ${Object.keys(levels).length} with a level.

/** market.php ITEM_MODIFY* field names that carry a rollable equipment stat. */
export type EquipmentStatKey = keyof typeof EQUIPMENT_STAT_LABELS;

export const EQUIPMENT_STAT_LABELS = ${JSON.stringify(EQUIPMENT_STAT_LABELS, null, 2)} as const;

/** Highest value a stat normally rolls at. A listing ABOVE this is a 破頂 (over-cap) item. */
export const EQUIPMENT_MAX_STATS: Record<string, Record<string, number> | { byItemId: Record<string, Record<string, number>> }> = ${JSON.stringify(EQUIPMENT_MAX_STATS, null, 2)};

/** Per-stat [min, max] roll range, from the guide's equipment catalogue. */
export const EQUIPMENT_STAT_RANGES: Record<string, Record<string, [number, number]>> = ${JSON.stringify(ranges, null, 2)};

/** Equipment level (the 等級 shown in the guide), by item name. */
export const EQUIPMENT_LEVELS: Record<string, number> = ${JSON.stringify(levels, null, 2)};

export const EQUIPMENT_DATA_VERSION = ${JSON.stringify(dataVersion)};
`;

const target = resolve(REPO, 'src/data/equipment-stats.ts');
writeFileSync(target, out);

console.log(`read     ${maxStatsSrc.from}`);
console.log(`read     ${catalogSrc.from}`);
console.log(`wrote    ${target}`);
console.log(`         version ${dataVersion} · ${Object.keys(EQUIPMENT_MAX_STATS).length} max-stat rows · ${Object.keys(ranges).length} range rows · ${Object.keys(levels).length} levels`);
